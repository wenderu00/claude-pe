// Regenerates the design system data from the pinned @uigovpe versions in ds.config.json:
// the skill's reference pages and hooks/pe/ds.generated.ts.
import { execSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { describeComponents, wrappers } from './ds/components.ts'
import { renderComponent, renderIndex, renderTokens, storiesFor, STORYBOOK } from './ds/reference.ts'
import type { StorybookIndex, Versions } from './ds/reference.ts'
import { extractTokens } from './ds/tokens.ts'

const ROOT = join(import.meta.dirname, '..')
const WORK = join(ROOT, '.sync-ds')
const REFS = join(ROOT, 'skills', 'pe-design-system', 'references')
const GENERATED = join(ROOT, 'hooks', 'pe', 'ds.generated.ts')
const INDEX_URL = STORYBOOK.replace(/index\.html$/, 'index.json')

function unpack(pkg: string, version: string): string {
  const dir = join(WORK, pkg.replace(/[@/]/g, '_'))
  mkdirSync(dir, { recursive: true })
  const out = execSync(`npm pack ${pkg}@${version} --ignore-scripts --json --pack-destination "${dir}"`, {
    cwd: WORK,
    encoding: 'utf8',
  })
  // npm < 12 prints an array; npm 12 an object keyed by package name.
  const parsed = JSON.parse(out) as { filename: string }[] | Record<string, { filename: string }>
  const { filename } = Array.isArray(parsed) ? parsed[0]! : Object.values(parsed)[0]!
  execSync(`tar -xzf "${filename}"`, { cwd: dir })
  return join(dir, 'package')
}

async function main(): Promise<void> {
  const versions = JSON.parse(readFileSync(join(ROOT, 'ds.config.json'), 'utf8')) as Versions
  rmSync(WORK, { recursive: true, force: true })
  mkdirSync(WORK, { recursive: true })

  const styles = unpack('@uigovpe/styles', versions.styles)
  const components = unpack('@uigovpe/components', versions.components)
  const response = await fetch(INDEX_URL)
  if (!response.ok) throw new Error(`${INDEX_URL}: HTTP ${response.status}`)
  const index = (await response.json()) as StorybookIndex

  const tokens = extractTokens(readFileSync(join(styles, 'dist', 'index.css'), 'utf8'))
  const dist = join(components, 'dist')
  const files: Record<string, string> = {}
  for (const f of readdirSync(dist)) if (f.endsWith('.d.ts')) files[`/pkg/${f}`] = readFileSync(join(dist, f), 'utf8')
  const docs = describeComponents(files, '/pkg/index.d.ts')

  const pages = join(REFS, 'components')
  rmSync(pages, { recursive: true, force: true })
  mkdirSync(pages, { recursive: true })
  for (const doc of docs) writeFileSync(join(pages, `${doc.name}.md`), renderComponent(doc, storiesFor(index, doc.name), versions))
  writeFileSync(join(pages, 'index.md'), renderIndex(docs, versions))
  writeFileSync(join(REFS, 'tokens.md'), renderTokens(tokens, versions))

  // An obsolete component is never the one to use instead.
  const wrapped = wrappers(docs.filter(d => !storiesFor(index, d.name)?.obsolete))
  const catalog = docs.map(d => {
    const s = storiesFor(index, d.name)
    return { name: d.name, docsUrl: s?.docsUrl ?? null, obsolete: s?.obsolete ?? false }
  })
  mkdirSync(join(ROOT, 'hooks', 'pe'), { recursive: true })
  writeFileSync(
    GENERATED,
    [
      '// Generated by `npm run sync-ds` from ds.config.json. Do not edit.',
      '',
      `export const DS_VERSIONS = ${JSON.stringify(versions)} as const`,
      '',
      `export const TOKENS: { light: Record<string, string>; dark: Record<string, string> } = ${JSON.stringify(tokens, null, 2)}`,
      '',
      '// primereact modules that @uigovpe/components wraps, and the components to import instead.',
      `export const WRAPPED_PRIMEREACT: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(wrapped, null, 2)}`,
      '',
      `export const COMPONENTS: readonly { name: string; docsUrl: string | null; obsolete: boolean }[] = ${JSON.stringify(catalog, null, 2)}`,
      '',
    ].join('\n'),
  )
  rmSync(WORK, { recursive: true, force: true })
  console.log(`sync-ds: ${docs.length} componentes, ${Object.keys(tokens.light).length} tokens, ${Object.keys(wrapped).length} módulos primereact`)
}

await main()
